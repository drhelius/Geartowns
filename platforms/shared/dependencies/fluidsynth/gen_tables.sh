#!/bin/sh

set -eu

FLUIDSYNTH_COMMIT=c3b244ddfd094489a5490beee013c621a504adf2
FLUIDSYNTH_REPOSITORY=https://github.com/FluidSynth/fluidsynth.git
GCEM_COMMIT=012ae73c6d0a2cb09ffe86475f5c6fba3926e200
GCEM_REPOSITORY=https://github.com/kthohr/gcem.git

SCRIPT_DIR=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
OUTPUT_FILE="$SCRIPT_DIR/fluid_tables.c"
TEMP_OUTPUT="$SCRIPT_DIR/fluid_tables.c.tmp"
CXX=${CXX:-c++}
WORK_DIR=

cleanup()
{
    rm -f "$TEMP_OUTPUT"

    if [ -n "$WORK_DIR" ]
    then
        rm -rf "$WORK_DIR"
    fi
}

trap cleanup EXIT HUP INT TERM

fetch_commit()
{
    repository=$1
    commit=$2
    directory=$3

    git init --quiet "$directory"
    git -C "$directory" fetch --quiet --depth 1 "$repository" "$commit"
    git -C "$directory" checkout --quiet --detach FETCH_HEAD

    if [ "$(git -C "$directory" rev-parse HEAD)" != "$commit" ]
    then
        echo "Unexpected commit in $repository" >&2
        exit 1
    fi
}

WORK_DIR=$(mktemp -d "${TMPDIR:-/tmp}/geartowns-fluidsynth.XXXXXX")

if [ "$#" -eq 0 ]
then
    FLUIDSYNTH_DIR="$WORK_DIR/fluidsynth-$FLUIDSYNTH_COMMIT"
    GCEM_DIR="$WORK_DIR/gcem-$GCEM_COMMIT"

    fetch_commit "$FLUIDSYNTH_REPOSITORY" "$FLUIDSYNTH_COMMIT" "$FLUIDSYNTH_DIR"
    fetch_commit "$GCEM_REPOSITORY" "$GCEM_COMMIT" "$GCEM_DIR"
elif [ "$#" -eq 2 ]
then
    FLUIDSYNTH_DIR=$1
    GCEM_DIR=$2
else
    echo "Usage: $0 [fluidsynth-$FLUIDSYNTH_COMMIT-source-dir gcem-$GCEM_COMMIT-source-dir]" >&2
    exit 1
fi

if [ ! -f "$FLUIDSYNTH_DIR/src/gentables/fluid_ct2hz.cpp" ] || [ ! -f "$GCEM_DIR/include/gcem.hpp" ]
then
    echo "Invalid FluidSynth or gcem source directory" >&2
    exit 1
fi

mkdir "$WORK_DIR/include" "$WORK_DIR/obj"
cp "$SCRIPT_DIR/src/utils/fluidsynth_config.h" "$WORK_DIR/include/config.h"

cat > "$WORK_DIR/dump.cpp" <<'DUMP'
#include <stdio.h>
#include <string.h>
#include "utils/fluid_conv_tables.h"
#include "fluidsynth_priv.h"

extern "C"
{
extern const fluid_real_t *const fluid_ct2hz_tab;
extern const fluid_real_t *const fluid_cb2amp_tab;
extern const fluid_real_t *const fluid_concave_tab;
extern const fluid_real_t *const fluid_convex_tab;
extern const fluid_real_t *const fluid_pan_tab;
extern const fluid_real_t *const interp_coeff;
extern const fluid_real_t *const interp_coeff_linear;
}

static void dump(const char *name, const fluid_real_t *table, int count)
{
    char text[64];

    printf("static const fluid_real_t %s_data[%d] =\n{", name, count);

    for (int i = 0; i < count; i++)
    {
        snprintf(text, sizeof(text), "%.9g", (double)table[i]);

        if (strpbrk(text, ".e") == NULL)
        {
            strcat(text, ".0");
        }

        printf("%s%sf", (i % 4) ? ", " : (i ? ",\n    " : "\n    "), text);
    }

    printf("\n};\n\nconst fluid_real_t *const %s = %s_data;\n\n", name, name);
}

int main()
{
    printf("/*\n");
    printf(" * ===========================================================================\n");
    printf(" *  GENERATED FILE, DO NOT EDIT\n");
    printf(" *\n");
    printf(" *  Generated by platforms/shared/dependencies/fluidsynth/gen_tables.sh from FluidSynth's gentables at\n");
    printf(" *  the pinned commit.\n");
    printf(" *  To change it, update the pinned commits in gen_tables.sh and run it again.\n");
    printf(" * ===========================================================================\n");
    printf(" */\n\n");
    printf("#include \"fluidsynth_priv.h\"\n\n");
    dump("fluid_ct2hz_tab", fluid_ct2hz_tab, FLUID_CENTS_HZ_SIZE);
    dump("fluid_cb2amp_tab", fluid_cb2amp_tab, FLUID_CB_AMP_SIZE);
    dump("fluid_concave_tab", fluid_concave_tab, FLUID_VEL_CB_SIZE);
    dump("fluid_convex_tab", fluid_convex_tab, FLUID_VEL_CB_SIZE);
    dump("fluid_pan_tab", fluid_pan_tab, FLUID_PAN_SIZE);
    dump("interp_coeff", interp_coeff, 256 * 4);
    dump("interp_coeff_linear", interp_coeff_linear, 256 * 2);
    return 0;
}
DUMP

set -- \
    -I"$WORK_DIR/include" \
    -I"$SCRIPT_DIR/include" \
    -I"$FLUIDSYNTH_DIR/include" \
    -I"$FLUIDSYNTH_DIR/src" \
    -I"$FLUIDSYNTH_DIR/src/utils" \
    -I"$FLUIDSYNTH_DIR/src/synth" \
    -I"$FLUIDSYNTH_DIR/src/rvoice" \
    -I"$FLUIDSYNTH_DIR/src/sfloader" \
    -I"$FLUIDSYNTH_DIR/src/midi" \
    -I"$FLUIDSYNTH_DIR/src/drivers" \
    -I"$FLUIDSYNTH_DIR/src/bindings" \
    -I"$GCEM_DIR/include"

OBJECTS=

for table in fluid_ct2hz fluid_cb2amp fluid_concave fluid_convex fluid_pan fluid_interp_coeff fluid_interp_coeff_linear
do
    "$CXX" -std=c++17 -O1 "$@" -c "$FLUIDSYNTH_DIR/src/gentables/$table.cpp" -o "$WORK_DIR/obj/$table.o"
    OBJECTS="$OBJECTS $WORK_DIR/obj/$table.o"
done

"$CXX" -std=c++17 -O1 "$@" -c "$WORK_DIR/dump.cpp" -o "$WORK_DIR/obj/dump.o"
"$CXX" -o "$WORK_DIR/dump" "$WORK_DIR/obj/dump.o" $OBJECTS
"$WORK_DIR/dump" > "$TEMP_OUTPUT"

mv "$TEMP_OUTPUT" "$OUTPUT_FILE"
trap - EXIT HUP INT TERM
cleanup
